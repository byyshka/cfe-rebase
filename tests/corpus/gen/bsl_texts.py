"""BSL texts of the synthetic corpus generator (build_corpus.py). Authoring conventions, applied by fmt():
  * leading groups of 4 spaces become tabs; "\\t" inside a line is a literal tab;
  * a line that is exactly "⇥" becomes a single tab (vendor-style blank line inside a method);
  * a line ending with "¶" is written with a bare LF (mixed line endings), the "¶" itself is dropped.
"""
import re


def fmt(text):
    out = []
    for line in text.split("\n"):
        if line == "⇥":
            out.append("\t")
            continue
        m = re.match(r"^((?: {4})+)", line)
        if m:
            line = "\t" * (len(m.group(1)) // 4) + line[len(m.group(1)):]
        out.append(line)
    return "\n".join(out)


def pick(new, old_text, new_text):
    return new_text if new else old_text


